/**
 * Preview what will be saved without actually saving
 * Useful for testing or showing user before confirming
 *
 * @param ctx - Task completion context
 * @returns Preview of what will be created
 */
export async function previewCompletion(ctx: TaskCompletionContext): Promise<{
  summary: TaskSummary | null;
  memoryObservations: string[];
  documentContent: string;
}> {
  const { task, chatMessages } = ctx;

  // Generate summary
  const summary = await generateTaskSummary(task, chatMessages);

  if (!summary) {
    return {
      summary: null,
      memoryObservations: [],
      documentContent: "",
    };
  }

  // Build memory observations
  const today = formatDateForFile(new Date());
  const memoryObservations: string[] = [
    `[${today}] Task: ${summary.title}`,
    `Summary: ${summary.summary}`,
  ];

  if (summary.accomplishments && summary.accomplishments.length > 0) {
    memoryObservations.push(
      `Accomplishments: ${summary.accomplishments.join("; ")}`
    );
  }

  // Build document content
  const documentContent = buildMarkdownDocument(task, summary, chatMessages);

  return {
    summary,
    memoryObservations,
    documentContent,
  };
}
