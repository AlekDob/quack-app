/**
 * Get marketplace resources with optional filtering
 */
export function getMarketplaceResources(filters?: {
  category?: string;
  featured?: boolean;
  verified?: boolean;
}): MarketplaceResource[] {
  let resources = [...MARKETPLACE_RESOURCES];

  if (filters?.category && filters.category !== 'all') {
    resources = resources.filter(r => r.category === filters.category);
  }

  if (filters?.featured) {
    resources = resources.filter(r => r.featured);
  }

  if (filters?.verified) {
    resources = resources.filter(r => r.verified);
  }

  return resources;
}

/**
 * Get total counts by category
 */
export function getCategoryCounts() {
  const counts: Record<string, number> = {
    all: MARKETPLACE_RESOURCES.length,
  };

  for (const resource of MARKETPLACE_RESOURCES) {
    counts[resource.category] = (counts[resource.category] || 0) + 1;
  }

  return counts;
}
